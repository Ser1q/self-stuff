#!/usr/bin/env bash
# Import snapshots of personal GitHub repos into this monorepo.
#
# Each repo listed in scripts/repos.tsv is shallow-cloned, copied into its
# destination folder without its git history, and committed as one commit.
# The original repos on GitHub are not changed.
#
# Usage: scripts/import-repos.sh [--dry-run] [repo ...]
#   --dry-run   show what would be imported, change nothing
#   repo ...    import only these repos (names as in repos.tsv)
#
# Safe to re-run: repos whose destination folder already exists are skipped.
set -euo pipefail

OWNER="Ser1q"
MAX_FILE_MB=10       # files larger than this are left out...
NOTEBOOK_MAX_MB=50   # ...except notebooks, which are kept up to this size

ROOT="$(git rev-parse --show-toplevel)"
MANIFEST="$ROOT/scripts/repos.tsv"
PATTERNS="$ROOT/scripts/secret-patterns.txt"
REPORT="$ROOT/scripts/import-report.md"
README_MARK="<!-- generated by scripts/import-repos.sh; edits above the index are kept -->"

DRY=0
ONLY=" "
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY=1 ;;
    -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    -*) echo "unknown option: $arg" >&2; exit 2 ;;
    *) ONLY="$ONLY$arg " ;;
  esac
done

WORK="$(mktemp -d "${TMPDIR:-/tmp}/import-repos.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

cd "$ROOT"

NOTES=""
note() { NOTES="$NOTES- $*"$'\n'; }

commit_paths() {  # commit_paths "subject" "body" path...
  local subject=$1 body=$2; shift 2
  git commit -q -m "$subject" -m "$body" -- "$@"
}

# --- initial commit ----------------------------------------------------------
if ! git rev-parse --verify -q HEAD >/dev/null; then
  if [[ $DRY == 1 ]]; then
    echo "would create the initial commit from the current files"
  else
    git add -A
    git commit -q -m "chore: initial project setup"
    echo "created initial commit"
  fi
fi

# --- import one repo ---------------------------------------------------------
REPORT_STARTED=0
report_header() {  # start a "## Run" section only when something is imported
  if [[ $REPORT_STARTED == 0 ]]; then
    [[ -f $REPORT ]] || printf '# Import report\n\nWhat changed while copying each repo in. Originals on GitHub are untouched.\n\n' >"$REPORT"
    printf '## Run %s\n\n' "$(date '+%Y-%m-%d %H:%M')" >>"$REPORT"
    REPORT_STARTED=1
  fi
}

import_one() {
  local repo=$1 dest=$2 src="$WORK/$1" try sha f rel bytes mb hits
  NOTES=""

  if [[ -e "$ROOT/$dest" ]]; then
    echo "skip    $repo ($dest already exists)"
    return 0
  fi
  if [[ $DRY == 1 ]]; then
    echo "would   $repo -> $dest"
    return 0
  fi
  report_header

  for try in 1 2 3; do
    rm -rf "$src"
    if gh repo clone "$OWNER/$repo" "$src" -- --depth 1 --quiet 2>"$WORK/clone.err"; then
      break
    fi
    if [[ $try == 3 ]]; then
      echo "FAILED  $repo: $(tail -1 "$WORK/clone.err")"
      printf '### %s\n- clone failed, not imported\n\n' "$repo" >>"$REPORT"
      return 1
    fi
    sleep $((try * 5))
  done

  sha=$(git -C "$src" rev-parse --short HEAD 2>/dev/null || echo "empty")
  rm -rf "$src/.git" "$src/.gitmodules"

  if [[ -z "$(find "$src" -mindepth 1 -print -quit)" ]]; then
    echo "empty   $repo (nothing to import)"
    printf '### %s\n- repo is empty, nothing imported\n\n' "$repo" >>"$REPORT"
    rm -rf "$src"
    return 0
  fi

  # Never bring env files across, even though .gitignore would hide them.
  while IFS= read -r f; do
    rm -f "$f"
    note "removed env file \`${f#"$src"/}\`"
  done < <(find "$src" -type f \( -name '.env' -o -name '.env.*' \) \
             ! -name '*.example' ! -name '*.sample' ! -name '*.template')

  # Leave out large files; the original repo still has them.
  while IFS= read -r f; do
    rel=${f#"$src"/}
    bytes=$(wc -c <"$f" | tr -d ' ')
    mb=$((bytes / 1048576))
    if [[ $f == *.ipynb && $mb -lt $NOTEBOOK_MAX_MB ]]; then
      note "kept large notebook \`$rel\` (${mb} MB)"
      continue
    fi
    rm -f "$f"
    note "left out \`$rel\` (${mb} MB)"
  done < <(find "$src" -type f -size +"${MAX_FILE_MB}"M)

  mkdir -p "$(dirname "$ROOT/$dest")"
  mv "$src" "$ROOT/$dest"

  git add -- "$dest"
  if git diff --cached --quiet -- "$dest"; then
    note "nothing committed: every file is covered by .gitignore"
  else
    hits=$(git grep --cached -lIE -f "$PATTERNS" -- "$dest" || true)
    if [[ -n $hits ]]; then
      while IFS= read -r f; do
        note "**possible secret** in \`$f\`: review before pushing"
      done <<<"$hits"
    fi
    commit_paths "import: $repo -> $dest" \
      "Snapshot of github.com/$OWNER/$repo at $sha, without git history." "$dest"
  fi

  printf '### %s -> `%s` (%s)\n%s\n' "$repo" "$dest" "$sha" "${NOTES:-- clean import}"$'\n' >>"$REPORT"
  if [[ $NOTES == *"possible secret"* ]]; then
    echo "done    $repo -> $dest  (check report: possible secret)"
  else
    echo "done    $repo -> $dest"
  fi
}

# --- run ---------------------------------------------------------------------
failed=0
while IFS=$'\t' read -r repo dest desc; do
  [[ -z $repo || $repo == \#* ]] && continue
  [[ $ONLY == " " || $ONLY == *" $repo "* ]] || continue
  import_one "$repo" "$dest" || failed=$((failed + 1))
done <"$MANIFEST"

[[ $DRY == 1 ]] && exit 0

# --- README index ------------------------------------------------------------
section_title() {
  case "$1" in
    learning) echo "Learning" ;;
    coursework) echo "Coursework" ;;
    experiments) echo "Experiments" ;;
    archive) echo "Archive (old or unused, read-only)" ;;
    *) echo "$1" ;;
  esac
}

index() {
  local section="" top
  echo "$README_MARK"
  echo
  echo "Each folder is a snapshot of an older GitHub repo; the original keeps the full history."
  while IFS=$'\t' read -r repo dest desc; do
    [[ -z $repo || $repo == \#* ]] && continue
    [[ -e "$ROOT/$dest" ]] || continue
    top=${dest%%/*}
    if [[ $top != "$section" ]]; then
      section=$top
      printf '\n## %s\n\n| Folder | What it is | Original repo |\n|---|---|---|\n' "$(section_title "$top")"
    fi
    printf '| [`%s`](%s) | %s | [%s](https://github.com/%s/%s) |\n' "$dest" "$dest" "$desc" "$repo" "$OWNER" "$repo"
  done <"$MANIFEST"
}

README="$ROOT/README.md"
if [[ ! -s $README ]]; then
  {
    printf '# self-stuff\n\nPersonal learning, coursework and experiments in one repo.\n\n'
    printf 'The root is a Python project managed with uv (`src/`). Imported folders keep their own dependency files.\n\n'
    index
  } >"$README"
elif grep -qF "$README_MARK" "$README"; then
  awk -v mark="$README_MARK" '$0 == mark { exit } { print }' "$README" >"$WORK/readme"
  index >>"$WORK/readme"
  mv "$WORK/readme" "$README"
else
  index >"$ROOT/scripts/index.md"
  echo "README.md has your own content; wrote the index to scripts/index.md instead"
fi

git add -- README.md scripts
if ! git diff --cached --quiet -- README.md scripts; then
  commit_paths "docs: index imported repos" \
    "Regenerate the README index and import report." README.md scripts
fi

echo
echo "report: scripts/import-report.md"
if [[ $failed -gt 0 ]]; then
  echo "$failed repo(s) failed to import; re-run the script to retry them"
  exit 1
fi
